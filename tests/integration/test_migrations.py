from __future__ import annotations

from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from sqlalchemy import inspect

import app.db.models  # noqa: F401 - registers tables
from app.core.config import Settings
from app.db.base import Base
from app.db.session import create_db_engine
from tests.conftest import alembic_config

PHASE1_TABLES = {
    "users",
    "user_preferences",
    "user_platforms",
    "providers",
    "titles",
    "title_availability",
    "interactions",
    "title_open_content",
}


def test_upgrade_creates_schema_on_fresh_sqlite_file(settings: Settings) -> None:
    command.upgrade(alembic_config(settings.database_url), "head")

    engine = create_db_engine(settings.database_url)
    try:
        insp = inspect(engine)
        assert set(insp.get_table_names()) == PHASE1_TABLES | {"alembic_version"}
        assert insp.get_view_names() == ["ratings"]
        assert {c["name"] for c in insp.get_columns("ratings")} == {
            "user_id",
            "tmdb_id",
            "type",
            "rating",
            "rated_at",
        }
        index_names = {ix["name"] for table in PHASE1_TABLES for ix in insp.get_indexes(table)}
        assert {
            "ix_interactions_user_id_created_at",
            "ix_title_availability_country_title",
            "ix_titles_original_language_type",
        } <= index_names
    finally:
        engine.dispose()


def test_migrated_schema_matches_models(settings: Settings) -> None:
    command.upgrade(alembic_config(settings.database_url), "head")
    engine = create_db_engine(settings.database_url)
    try:
        with engine.connect() as conn:
            ctx = MigrationContext.configure(conn, opts={"compare_type": True})
            diff = [
                d
                for d in compare_metadata(ctx, Base.metadata)
                # The view reflects as a table only on some backends; never autogenerated.
                if not (d[0] == "remove_table" and d[1].name == "ratings")
            ]
        assert diff == []
    finally:
        engine.dispose()


def test_downgrade_removes_everything_and_upgrade_is_repeatable(settings: Settings) -> None:
    cfg = alembic_config(settings.database_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")

    engine = create_db_engine(settings.database_url)
    try:
        insp = inspect(engine)
        assert set(insp.get_table_names()) == {"alembic_version"}
        assert insp.get_view_names() == []
    finally:
        engine.dispose()

    command.upgrade(cfg, "head")
    engine = create_db_engine(settings.database_url)
    try:
        assert set(inspect(engine).get_table_names()) >= PHASE1_TABLES
    finally:
        engine.dispose()
